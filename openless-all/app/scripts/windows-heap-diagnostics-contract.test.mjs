import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import yaml from 'js-yaml';

const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8');
const release = yaml.load(read('../../../.github/workflows/release-tauri.yml'));
const ci = yaml.load(read('../../../.github/workflows/ci.yml'));
const module = read('../src-tauri/src/issue1261_debug.rs');
const recorder = read('../src-tauri/src/recorder.rs');
const host = read('../src-tauri/src/tauri_coordinator_host.rs');
const ipc = read('../src-tauri/src/windows_ime_ipc.rs');
const cargo = read('../src-tauri/Cargo.toml');

assert.equal(release.on.workflow_dispatch.inputs.windows_heap_diagnostics.default, false);
assert.match(cargo, /default = \["custom-protocol"\]/);
assert.match(cargo, /issue-1261-diagnostics = \[\]/);
const build = release.jobs.build.steps.find((step) => step.name === 'Build (Windows)');
for (const guard of ["github.event_name == 'workflow_dispatch'", "startsWith(github.ref, 'refs/heads/')", "inputs.release_tag == ''"])
  assert.ok(build.env.WINDOWS_HEAP_DIAGNOSTICS.includes(guard));
assert.match(build.run, /diagnostic_args=\(\)/);
assert.match(build.run, /--features issue-1261-diagnostics/);
const bundleCommands = build.run.split('\n').filter((line) => line.includes('npm run tauri -- build --bundles'));
assert.equal(bundleCommands.length, 4);
assert.ok(bundleCommands.every((line) => line.includes('"${diagnostic_args[@]}"')));
const verify = release.jobs.build.steps.find((step) => step.name === 'Verify Windows diagnostic symbols');
assert.match(verify.run, /python -I .*windows-symbol-pair\.py/);
assert.match(verify.run, /--revision "\$OPENLESS_BUILD_ID"/);
assert.match(verify.run, /python -I release-tooling\/openless-all\/app\/scripts\/windows-symbol-pair\.py/);
const tooling = release.jobs.build.steps.find((step) => step.name === 'Fetch Windows symbol tooling');
assert.equal(tooling.if, "matrix.platform == 'windows-latest'");
assert.equal(tooling.env.TOOLING_SHA, '${{ github.workflow_sha }}');
assert.match(tooling.run, /\$scriptPath = 'openless-all\/app\/scripts\/windows-symbol-pair\.py'/);
assert.match(tooling.run, /--method GET -f "ref=\$env:TOOLING_SHA"/);
assert.match(tooling.run, /WriteAllBytes\(\$destination, \$bytes\)/);
assert.equal(release.jobs.build.steps.find((step) => step.uses === 'actions/checkout@v4').with.ref, '${{ inputs.release_tag || github.sha }}');
assert.match(release.jobs.build.steps.find((step) => step.name === 'Upload Windows artifacts').with.path, /windows-symbols\.json/);
const ciSteps = ci.jobs['cross-platform'].steps;
assert.ok(ciSteps.some((step) => step.run?.includes('--features issue-1261-diagnostics')));
assert.ok(ciSteps.some((step) => step.run === 'python -I scripts/windows-symbol-pair.test.py'));
assert.match(module, /cfg!\(all\(\s*target_os = "windows",\s*feature = "issue-1261-diagnostics",\s*not\(test\)\s*\)\)/);
assert.match(module, /sync_channel\(QUEUE_CAPACITY\)/);
assert.match(module, /sender\.try_send\(record\)/);
assert.match(module, /openless-issue-1261-9e0ffd34-session\.ndjson/);
assert.doesNotMatch(module, /std::process::id\(|var_os\(|setTimeout|thread::sleep/);
assert.match(module, /enum Fact \{\s*Count\(u64\),\s*Flag\(bool\),?\s*\}/);
assert.match(module, /enum Probe \{\s*Capture,\s*Audio,\s*Main,\s*Ime,?\s*\}/);
assert.match(recorder, /probe\.callback\(data\.len\(\)\)/);
assert.match(recorder, /probe\.output\(chunk\.pcm_i16_le\.len\(\)\)/);
assert.match(host, /run_on_main_thread_for_probe\(2,/);
assert.match(host, /Event::DispatchReturned/);
assert.match(host, /Event::EpochSkipped/);
assert.match(ipc, /Event::ImeReturned/);
assert.match(ipc, /Key::OutcomeUnknown/);
console.log('windows-heap-diagnostics-contract.test.mjs passed');
